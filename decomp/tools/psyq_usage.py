#!/usr/bin/env python3
"""List the PsyQ library functions the game calls, grouped by library.

The port replaces these functions instead of recompiling them, so this is the
work list for the platform layer. Library code is found with the
ghidra_psx_ldr signatures (see psyq_sigmatch.py) in the boot executable and
in ENGINE1/ENGINE3/TITLE (each engine carries a few own copies); the level
overlays hold none. Every `jal` in the executables and overlays is then
resolved (calls from inside library objects are left out, only game code
counts): below 0x80038350 to the boot executable, above to the engine the
code runs with (OV2/OV8/OV10 with ENGINE3, the other overlays with ENGINE1).

    python3 tools/psyq_usage.py SIG_ROOT [--version 370] [--out docs/psyq_usage.md]

SIG_ROOT: ghidra_psx_ldr/data/psyq (from ~/psx-decomp/tools/ghidra_psx_ldr.zip)
"""
import argparse
import collections
import json
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from psyq_sigmatch import INTERNAL_LABEL, load_exe, match_version  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
ENGINE_BASE = 0x80038350
IMAGES = {
    "SCES_008.93": "files/SCES_008.93",
    "ENGINE1": "files/EX/ENGINE1.",
    "ENGINE3": "files/EX/ENGINE3.",
    "TITLE": "files/EX/TITLE.",
}
ENGINE3_OVERLAYS = {2, 8, 10}


def jal_targets(data, base):
    """(call site, target) of every jal in a code image loaded at base."""
    words = struct.unpack_from(f"<{len(data) // 4}I", data)
    return [(base + 4 * i, ((w & 0x3FFFFFF) << 2) | 0x80000000) for i, w in enumerate(words) if w >> 26 == 3]


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("sig_root", type=Path)
    ap.add_argument("--version", default="370")
    ap.add_argument("--out", type=Path)
    args = ap.parse_args()

    vdir = args.sig_root / args.version
    sig_len = {f"{lib.stem}:{e['name']}": len(e.get("sig", "").split())
               for lib in vdir.glob("*.json") for e in json.loads(lib.read_text())}
    # (image, address) -> (function, library); spans of library objects per image
    library, spans = {}, collections.defaultdict(list)
    for image, path in IMAGES.items():
        text, base = load_exe(ROOT / path)
        for key, (addr, labels) in match_version(text, base, vdir).items():
            lib = key.split(":")[0].removesuffix(".LIB")
            spans[image].append((addr, addr + sig_len[key]))
            for label in labels:
                if not INTERNAL_LABEL.match(label["name"]):
                    library.setdefault((image, addr + label["offset"]), (label["name"], lib))

    callers = [(image, *load_exe(ROOT / path), image) for image, path in IMAGES.items()]
    for i in range(12):
        data = (ROOT / f"files/OV/OV{i}.").read_bytes()
        host = "ENGINE3" if i in ENGINE3_OVERLAYS else "ENGINE1"
        callers.append((f"OV{i}", data[: len(data) // 4 * 4], 0x800684A0 if host == "ENGINE3" else 0x80074A4C, host))

    used = collections.defaultdict(set)
    for name, data, base, host in callers:
        for site, target in jal_targets(data, base):
            if any(a <= site < b for a, b in spans[name]):
                continue  # call between library functions, not from game code
            image = "SCES_008.93" if target < ENGINE_BASE else host
            hit = library.get((image, target))
            if hit:
                used[hit].add(name)

    by_lib = collections.defaultdict(list)
    for (func, lib), who in used.items():
        by_lib[lib].append((func, who))
    order = ["SCES_008.93", "ENGINE1", "ENGINE3", "TITLE"] + [f"OV{i}" for i in range(12)]
    lines = [
        "# PsyQ functions called by the game",
        "",
        f"Generated by `tools/psyq_usage.py` (PsyQ {args.version[0]}.{args.version[1:]} signatures). "
        "Library code lives in SCES_008.93 and, for a few functions, in the engines; "
        "the overlays contain none. Only calls from game code are listed (library-internal calls are left out). "
        "These are the functions the platform layer has to provide.",
        "",
        f"{sum(len(v) for v in by_lib.values())} functions in {len(by_lib)} libraries.",
        "",
        "| Library | Functions |",
        "|---------|----------:|",
    ] + [f"| {lib} | {len(by_lib[lib])} |" for lib in sorted(by_lib)] + [""]
    for lib in sorted(by_lib):
        lines += [f"## {lib}", "", "| Function | Called from |", "|----------|-------------|"]
        for func, who in sorted(by_lib[lib]):
            lines.append(f"| `{func}` | {', '.join(sorted(who, key=order.index))} |")
        lines.append("")
    text = "\n".join(lines)
    if args.out:
        args.out.write_text(text)
        print(f"{args.out}: {sum(len(v) for v in by_lib.values())} functions in {len(by_lib)} libraries")
    else:
        print(text)


if __name__ == "__main__":
    main()
