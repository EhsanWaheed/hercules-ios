#!/usr/bin/env python3
"""Generate hl_strings.h from launcher/web/i18n.js (the one place the texts live).

    python3 launcher_native/gen_strings.py      (needs node)
"""
import json
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
JS = HERE.parent / "launcher/web/i18n.js"
dump = subprocess.run(
    ["node", "-e", "const vm=require('vm'),fs=require('fs');"
     "const c={};vm.createContext(c);vm.runInContext(fs.readFileSync(process.argv[1],'utf8')"
     "+';this.OUT={LANGS,LEVEL_KEYS,STR};',c);console.log(JSON.stringify(c.OUT))", str(JS)],
    check=True, capture_output=True, text=True).stdout
data = json.loads(dump)


def flat(prefix, v, out):
    if isinstance(v, dict):
        for k, x in v.items():
            flat(f"{prefix}{k}.", x, out)
    elif isinstance(v, list):
        for i, x in enumerate(v):
            flat(f"{prefix}{i}.", x, out)
    else:
        out[prefix[:-1]] = v


def lit(s):
    return json.dumps(s, ensure_ascii=False)


lines = ["// Generated by gen_strings.py from launcher/web/i18n.js -- do not edit.",
         "#pragma once", "#include <map>", "#include <string>", "", "namespace hl {", "",
         "struct LangName { const char* code; const char* name; };",
         "static const LangName kLangs[] = {"]
lines += [f"    {{{lit(c)}, {lit(n)}}}," for c, n in data["LANGS"]]
lines += ["};", "static const char* const kLevelKeys[] = {" + ", ".join(lit(k) for k in data["LEVEL_KEYS"]) + "};",
          "", "// language -> key (dotted path, lists as .0 .1 ...) -> text",
          "static const std::map<std::string, std::map<std::string, std::string>> kStrings = {"]
for lang, tree in data["STR"].items():
    out = {}
    flat("", tree, out)
    lines.append(f"    {{{lit(lang)}, {{")
    lines += [f"        {{{lit(k)}, {lit(v)}}}," for k, v in sorted(out.items())]
    lines.append("    }},")
lines += ["};", "", "}  // namespace hl", ""]
(HERE / "hl_strings.h").write_text("\n".join(lines))
print(f"hl_strings.h: {len(data['STR'])} languages")
